export const normalizeAsignatura = (name) => {
  if (!name) return 'General';
  const n = String(name).trim().toLowerCase()
    .normalize("NFD").replace(/[\u0300-\u036f]/g, ""); // quita tildes
  
  if (n.includes('logico') || n.includes('logica')) return 'Raz. Lógico';
  if (n.includes('raz. mat') || n.includes('razonamiento mat') || n.includes('matematico')) return 'Raz. Matemático';
  if (n.includes('comp') && n.includes('lect')) return 'Comp. Lectora';
  if (n.includes('verbal') || n.includes('raz. verbal') || n.includes('razonamiento verb')) return 'Raz. Verbal';
  if (n.includes('algebra')) return 'Álgebra';
  if (n.includes('aritmetica')) return 'Aritmética';
  if (n.includes('geometria')) return 'Geometría';
  if (n.includes('trigono')) return 'Trigonometría';
  if (n.includes('historia')) return 'Historia';
  if (n.includes('geografia')) return 'Geografía';
  if (n.includes('quimica')) return 'Química';
  if (n.includes('biologia')) return 'Biología';
  if (n.includes('fisica')) return 'Física';
  if (n.includes('filosofia')) return 'Filosofía';
  if (n.includes('psicologia')) return 'Psicología';
  if (n.includes('civica') || n.includes('ciudadan')) return 'Ed. Cívica';
  if (n.includes('lenguaje') || n.includes('comunicacion')) return 'Lenguaje';
  if (n.includes('literatura')) return 'Literatura';
  if (n.includes('ingles') || n.includes('gramatica')) return 'Gramática';
  if (n.includes('lectura')) return 'Lectura';

  return String(name).trim();
};

export const calculateExamScore = ({ questions = [], userAnswers = {}, area = 'Sociales', simData = datosSimulador }) => {
  let correctCount = 0;
  let wrongCount = 0;
  let blankCount = 0;
  const aciertosPorAsignatura = {};
  const totalPorAsignatura = {};

  const cleanOptionTextLocal = (text) => {
    if (!text) return '';
    return String(text).replace(/^[A-Ea-e][\)\.\:\-]\s*|^\([A-Ea-e]\)\s*/, '').trim();
  };

  const normalizeAnsIndexLocal = (ans, options = null) => {
    if (ans === undefined || ans === null) return 0;
    if (Array.isArray(options) && typeof ans === 'string') {
      const cleanAns = cleanOptionTextLocal(ans).toLowerCase();
      const foundIdx = options.findIndex(opt => {
        const cleanOpt = cleanOptionTextLocal(opt).toLowerCase();
        return cleanOpt === cleanAns || cleanOpt === String(ans).trim().toLowerCase();
      });
      if (foundIdx !== -1) return foundIdx;
    }
    if (typeof ans === 'number') {
      if (Array.isArray(options) && ans > options.length - 1 && ans <= options.length) {
        return ans - 1;
      }
      return Math.max(0, ans);
    }
    const str = String(ans).trim().toUpperCase();
    const letterMatch = str.match(/([A-E])/);
    if (letterMatch && (str.length <= 8 || str.includes('CLAVE') || str.includes('OPCI') || str.includes('RESPUESTA'))) {
      const char = letterMatch[1];
      if (char === 'A') return 0;
      if (char === 'B') return 1;
      if (char === 'C') return 2;
      if (char === 'D') return 3;
      if (char === 'E') return 4;
    }
    const parsed = parseInt(str, 10);
    if (!isNaN(parsed)) {
      if (Array.isArray(options) && parsed > options.length - 1 && parsed <= options.length) {
        return parsed - 1;
      }
      return Math.max(0, parsed);
    }
    return 0;
  };

  const details = questions.map((q, idx) => {
    const userChoice = userAnswers[idx];
    const isBlank = userChoice === undefined || userChoice === null;
    const userChoiceNorm = !isBlank ? normalizeAnsIndexLocal(userChoice, q.options) : null;
    const correctChoiceNorm = normalizeAnsIndexLocal(q.answer ?? q.ans, q.options);

    let isCorrect = false;
    if (!isBlank && userChoiceNorm !== null) {
      if (userChoiceNorm === correctChoiceNorm) {
        isCorrect = true;
      } else if (Array.isArray(q.options) && q.options[userChoiceNorm] && q.options[correctChoiceNorm]) {
        const textUser = cleanOptionTextLocal(q.options[userChoiceNorm]).toLowerCase();
        const textCorrect = cleanOptionTextLocal(q.options[correctChoiceNorm]).toLowerCase();
        if (textUser === textCorrect && textUser.length > 0) {
          isCorrect = true;
        }
      }
    }

    const asig = q.asignaturaOficial || normalizeAsignatura(q.asignatura || q.subject || q.curso || 'General');
    totalPorAsignatura[asig] = (totalPorAsignatura[asig] || 0) + 1;
    if (isCorrect) {
      aciertosPorAsignatura[asig] = (aciertosPorAsignatura[asig] || 0) + 1;
      correctCount++;
    } else if (isBlank) {
      blankCount++;
    } else {
      wrongCount++;
    }

    return {
      question: q.q,
      imageUrl: q.imageUrl || q.img || '',
      options: q.options || [],
      userChoice: userChoiceNorm,
      correctChoice: correctChoiceNorm,
      isCorrect,
      isBlank,
      explanation: q.explanation || q.solucion || '',
      asignatura: asig,
      valorPonderado: q.valorPonderado || null,
      authorName: q.authorName || 'Comunidad RASTRO'
    };
  });

  // Cálculo ponderado oficial UNSA
  let unsaWeightedScore = 0;
  let hasMatchingWeights = false;

  // Si cada pregunta ya trae su propio valor ponderado oficial (Modo Simulacro Oficial 80)
  const hasQuestionWeights = questions.some(q => typeof q.valorPonderado === 'number');
  if (hasQuestionWeights) {
    questions.forEach((q, idx) => {
      const isCorrect = details[idx]?.isCorrect;
      if (isCorrect) {
        unsaWeightedScore += (q.valorPonderado || 0);
        hasMatchingWeights = true;
      }
    });
  } else {
    const areaConfig = simData[area] || simData['Sociales'] || [];
    areaConfig.forEach(item => {
      const asigAciertos = aciertosPorAsignatura[item.asignatura] || 0;
      if (asigAciertos > 0) {
        hasMatchingWeights = true;
        unsaWeightedScore += asigAciertos * item.valor;
      }
    });
  }

  // Si las preguntas no tenían asignaturas que empaten con la tabla UNSA, calculamos sobre base 100 simple:
  if (!hasMatchingWeights && questions.length > 0) {
    unsaWeightedScore = (correctCount / questions.length) * 100;
  }

  if (unsaWeightedScore > 100) unsaWeightedScore = 100;

  const percentage = questions.length > 0 ? Math.round((correctCount / questions.length) * 100) : 0;

  return {
    total: questions.length,
    score: correctCount,
    correctCount,
    wrongCount,
    blankCount,
    unsaWeightedScore: Number(unsaWeightedScore.toFixed(4)),
    percentage,
    aciertosPorAsignatura,
    totalPorAsignatura,
    details
  };
};

