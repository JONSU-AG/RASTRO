export const generateSimulacroOficial80 = (bancoPreguntas = [], area = 'Biomédicas', orderPreference = 'aleatorio') => {
  const areaRules = datosSimulador[area] || datosSimulador['Biomédicas'] || [];
  const selectedQuestions = [];
  const usedIds = new Set();

  const shuffle = (array) => {
    const arr = [...array];
    for (let i = arr.length - 1; i > 0; i--) {
      const j = Math.floor(Math.random() * (i + 1));
      [arr[i], arr[j]] = [arr[j], arr[i]];
    }
    return arr;
  };

  // Agrupar preguntas por asignatura normalizada
  const bancoByAsignatura = {};
  bancoPreguntas.forEach(q => {
    const asig = normalizeAsignatura(q.asignatura || q.subject || q.curso);
    if (!bancoByAsignatura[asig]) bancoByAsignatura[asig] = [];
    bancoByAsignatura[asig].push(q);
  });

  areaRules.forEach(rule => {
    const targetAsig = rule.asignatura;
    const countNeeded = rule.preguntas;

    let candidates = bancoByAsignatura[targetAsig] || [];

    // Fallbacks inteligentes si una subespecialidad tiene pocos registros
    if (candidates.length < countNeeded) {
      if (['Aritmética', 'Geometría', 'Trigonometría'].includes(targetAsig)) {
        candidates = [
          ...candidates,
          ...(bancoByAsignatura['Álgebra'] || []),
          ...(bancoByAsignatura['Raz. Matemático'] || [])
        ];
      } else if (targetAsig === 'Comp. Lectora') {
        candidates = [
          ...candidates,
          ...(bancoByAsignatura['Raz. Verbal'] || []),
          ...(bancoByAsignatura['Lectura'] || [])
        ];
      } else if (targetAsig === 'Gramática') {
        candidates = [
          ...candidates,
          ...(bancoByAsignatura['Lenguaje'] || []),
          ...(bancoByAsignatura['Lectura'] || [])
        ];
      } else if (targetAsig === 'Lectura') {
        candidates = [
          ...candidates,
          ...(bancoByAsignatura['Gramática'] || []),
          ...(bancoByAsignatura['Lenguaje'] || [])
        ];
      }
    }

    const unused = candidates.filter(q => !usedIds.has(q.id));
    const pool = unused.length >= countNeeded ? unused : (candidates.length > 0 ? candidates : bancoPreguntas);
    const shuffled = shuffle(pool);
    const picked = shuffled.slice(0, countNeeded);

    picked.forEach(q => {
      usedIds.add(q.id);
      selectedQuestions.push({
        ...q,
        area,
        asignaturaOficial: targetAsig,
        cursoOficial: rule.curso,
        valorPonderado: rule.valor
      });
    });
  });

  // Ordenamiento según preferencia del estudiante
  if (orderPreference === 'aleatorio') {
    return shuffle(selectedQuestions);
  }

  if (orderPreference === 'letras_primero') {
    const getLetrasPriority = (q) => {
      const c = (q.cursoOficial || '').toLowerCase();
      if (c.includes('comunicación') || c.includes('sociales') || c.includes('persona')) return 1;
      if (c.includes('aptitud')) return 2;
      if (c.includes('ciencia')) return 3;
      if (c.includes('matemática')) return 4;
      return 5;
    };
    return [...selectedQuestions].sort((a, b) => getLetrasPriority(a) - getLetrasPriority(b));
  }

  if (orderPreference === 'ciencias_primero') {
    const getCienciasPriority = (q) => {
      const c = (q.cursoOficial || '').toLowerCase();
      if (c.includes('ciencia') || c.includes('matemática')) return 1;
      if (c.includes('aptitud')) return 2;
      if (c.includes('comunicación') || c.includes('sociales') || c.includes('persona')) return 3;
      return 4;
    };
    return [...selectedQuestions].sort((a, b) => getCienciasPriority(a) - getCienciasPriority(b));
  }

  // Por defecto 'oficial': Orden oficial fijado por la UNSA
  return selectedQuestions;
};

